import type { ReactNode } from "react";
import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useState,
} from "react";
import {
  defaultSiteSettings,
  type ResolvedSiteSettings,
} from "../../config/siteSettings";
import { typographyVars } from "../../config/siteType";
import { findFont } from "../../config/theme";
import { settingsApi } from "../services/portfolioService";
import { siteConfig } from "../site";
import { loadFont } from "./fonts";
import { loadFontRef } from "./remoteFonts";

interface SiteSettingsContextValue {
  /** True until the first fetch settles; the built-in defaults render meanwhile. */
  isLoading: boolean;
  reload: () => Promise<void>;
  /** Replaces the active settings after an admin saves, with no refetch. */
  setSettings: (next: ResolvedSiteSettings) => void;
  settings: ResolvedSiteSettings;
}

const SiteSettingsContext = createContext<SiteSettingsContextValue | null>(
  null
);

/**
 * Applies the theme by overriding the palette variables in src/index.css, so
 * every existing `bg-background` / `text-foreground` / `font-sans` utility
 * follows along without touching a component.
 *
 * The names are the semantic ones — `--background`, not `--color-background`.
 * That block is `@theme inline`, which substitutes the value into each utility
 * rather than emitting a second variable: `bg-background` compiles to
 * `background-color: var(--background)`, and `--color-background` exists
 * nowhere in the built stylesheet. Setting it would do nothing at all, and
 * nothing would say so.
 *
 * This is why the theme is stored as colors rather than Tailwind class names:
 * utilities are generated by scanning source at build time, so a class that
 * exists only in a database row would never be emitted.
 */
/** The --type-* and font variables the last typography set, to clear. */
let typeVars: string[] = [];

/**
 * The brand kit's faces and type scale, over the theme's fonts
 * (config/siteType.ts). Runs after the theme's own fonts are set, so the
 * kit's headline and body faces win; with no kit, the variables it set last
 * time are removed and the pages fall back to their own sizes.
 */
const applyTypography = (settings: ResolvedSiteSettings): void => {
  const root = document.documentElement;
  const { typography } = settings;
  const vars = typography ? typographyVars(typography) : {};
  for (const name of typeVars) {
    // The font variables were just set from the theme; leave those.
    if (!(name in vars || name.startsWith("--font-"))) {
      root.style.removeProperty(name);
    }
  }
  for (const [name, value] of Object.entries(vars)) {
    root.style.setProperty(name, value);
  }
  typeVars = Object.keys(vars);
  loadFontRef(typography?.headline?.ref);
  loadFontRef(typography?.body?.ref);
};

const applyTheme = (settings: ResolvedSiteSettings): void => {
  const { theme } = settings;
  const root = document.documentElement;

  /*
   * Both names, deliberately.
   *
   * `--background` is what the palette in index.css declares and what
   * `bg-background` compiles to under `@theme inline`. `--color-background` is
   * the name Tailwind emits for anything that still reads the alias — some
   * utilities do, and hand-written CSS elsewhere in the app does.
   *
   * Setting only one of them is how the admin turned white: its chrome is built
   * entirely from `text-white/90` and `bg-black/40`, which only work over a
   * dark ground, and that ground comes from here rather than from the
   * light/dark switch. Writing both costs three lines and cannot be half-right.
   */
  for (const [name, value] of [
    ["background", theme.background],
    ["foreground", theme.foreground],
    ["accent", theme.accent],
  ] as const) {
    root.style.setProperty(`--${name}`, value);
    root.style.setProperty(`--color-${name}`, value);
  }

  const sans = findFont(theme.sansFont);
  const serif = findFont(theme.serifFont);
  const display = findFont(theme.displayFont) ?? sans;
  if (sans) {
    root.style.setProperty("--font-sans", sans.stack);
  }
  if (serif) {
    root.style.setProperty("--font-serif", serif.stack);
  }
  if (display) {
    root.style.setProperty("--font-display", display.stack);
  }

  void loadFont(theme.sansFont);
  void loadFont(theme.serifFont);
  void loadFont(theme.displayFont);

  applyTypography(settings);

  document
    .querySelector('meta[name="theme-color"]')
    ?.setAttribute("content", theme.background);
};

export function SiteSettingsProvider({ children }: { children: ReactNode }) {
  // First paint uses the values compiled into the bundle, so the page is never
  // blank and never unstyled while the request is in flight.
  const [settings, setSettingsState] = useState<ResolvedSiteSettings>(() =>
    defaultSiteSettings(siteConfig)
  );
  const [isLoading, setIsLoading] = useState(true);

  const setSettings = useCallback((next: ResolvedSiteSettings) => {
    setSettingsState(next);
    applyTheme(next);
    document.title = next.name;
  }, []);

  const reload = useCallback(async () => {
    try {
      const fetched = await settingsApi.get();
      // A 200 carrying the wrong shape — a stale cache, a partial deploy, an
      // intercepting proxy — must not take the site down. applyTheme reads
      // theme.background directly, so an absent theme would throw during
      // render and leave a blank page.
      if (!fetched.theme) {
        throw new Error("Site settings response is missing a theme");
      }
      setSettings(fetched);
    } catch {
      // Keep whatever is already rendering: stale settings beat no site.
    } finally {
      setIsLoading(false);
    }
  }, [setSettings]);

  // Paints the compiled defaults immediately, then fetches the live values.
  //
  // This must not depend on `settings`. reload() replaces them with a freshly
  // parsed object, so a `settings` dependency re-runs the effect, which fetches
  // again, forever — a request loop that hammers the API for as long as the tab
  // is open. Reading the defaults straight from the module keeps the dependency
  // list honest rather than suppressed: on mount `settings` IS this value, and
  // reload() re-applies the theme once the response lands.
  useEffect(() => {
    applyTheme(defaultSiteSettings(siteConfig));
    void reload();
  }, [reload]);

  const value = useMemo(
    () => ({ isLoading, reload, setSettings, settings }),
    [settings, isLoading, setSettings, reload]
  );

  return (
    <SiteSettingsContext.Provider value={value}>
      {children}
    </SiteSettingsContext.Provider>
  );
}

/** Live site settings. Falls back to compiled defaults outside the provider. */
export const useSiteSettings = (): SiteSettingsContextValue => {
  const ctx = useContext(SiteSettingsContext);
  if (ctx) {
    return ctx;
  }
  return {
    isLoading: false,
    reload: async () => undefined,
    setSettings: () => undefined,
    settings: defaultSiteSettings(siteConfig),
  };
};
