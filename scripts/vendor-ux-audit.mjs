#!/usr/bin/env node
/**
 * Copies the UX audit framework, verbatim, to the two places that use it:
 * api/_lib/uxAudit/vendor/ (the site's screen audit, as modules) and
 * agents/audit/agent/instructions/references/ (the eve agent, as markdown
 * that agent/instructions/10-references.ts loads into its context).
 *
 * The audit prompt is built from Dallas's ux-audit skill and the design
 * references of ux-audit-app. They are copied into modules rather than read
 * at runtime so the function bundle carries them with no includeFiles setup.
 * Edit the sources, then run this again; never edit the vendor files.
 *
 *   node scripts/vendor-ux-audit.mjs [skillDir] [appDir]
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const dev = join(homedir(), "Development");
const skill =
  process.argv[2] ??
  join(dev, "ux-audits/rolemodel-design-audit/skills/ux-audit");
const app = process.argv[3] ?? join(dev, "ux-audit-app");
const out = join(import.meta.dirname, "../api/_lib/uxAudit/vendor");
const agentOut = join(
  import.meta.dirname,
  "../agents/audit/agent/instructions/references"
);
mkdirSync(agentOut, { recursive: true });

const TS_EXTENSION = /\.ts$/;

const escapeTemplate = (text) =>
  text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");

const write = (file, name, source, text, { toAgent = true } = {}) => {
  if (toAgent) {
    writeFileSync(
      join(agentOut, file.replace(TS_EXTENSION, ".md")),
      `${text.trim()}\n`
    );
  }
  writeFileSync(
    join(out, file),
    `/**\n * ${source}, verbatim. Generated by scripts/vendor-ux-audit.mjs; do not edit.\n */\nexport const ${name} = \`${escapeTemplate(text.trim())}\n\`;\n`
  );
  console.log(`${file}  ${text.length} chars  ← ${source}`);
};

for (const [file, name] of [
  ["laws-of-ux", "LAWS_OF_UX"],
  ["tone-guide", "TONE_GUIDE"],
  ["severity-model", "SEVERITY_MODEL"],
  ["audit-checklist", "AUDIT_CHECKLIST"],
  ["team-guide", "TEAM_GUIDE"],
]) {
  write(
    `${file}.ts`,
    name,
    `ux-audit skill references/${file}.md`,
    readFileSync(join(skill, "references", `${file}.md`), "utf8")
  );
}

// Phase 3 of the skill: the ten-section heuristic audit.
const skillMd = readFileSync(join(skill, "SKILL.md"), "utf8");
const start = skillMd.indexOf("## Phase 3: Heuristic Audit");
const end = skillMd.indexOf("## Phase 4:");
if (start < 0 || end < start) {
  throw new Error("SKILL.md no longer has Phase 3 followed by Phase 4");
}
write(
  "heuristic-audit.ts",
  "HEURISTIC_AUDIT",
  "ux-audit skill SKILL.md, Phase 3",
  skillMd.slice(start, end)
);

const refs = join(app, "references");
for (const f of readdirSync(refs).filter((name) => name.endsWith(".md"))) {
  writeFileSync(join(agentOut, f), readFileSync(join(refs, f), "utf8"));
}
const designRefs = readdirSync(refs)
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => readFileSync(join(refs, f), "utf8").trim())
  .join("\n\n---\n\n");
write(
  "design-references.ts",
  "DESIGN_REFERENCES",
  "ux-audit-app references/*.md",
  designRefs,
  // The agent reads the twelve files one by one instead.
  { toAgent: false }
);
