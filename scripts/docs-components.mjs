/**
 * Writes the docs site's Components tab from the brand kits.
 *
 * Reads the public feed (`/api/brand-kits?docs=components`) and writes one
 * page per kit with component styles: each style drawn live, then its React
 * and CSS in a code group with Mintlify's copy button. A kit gets a page as
 * soon as it has a style, and loses it when it has none.
 *
 * Plain Node, no dependencies, so the scheduled workflow
 * (.github/workflows/docs-components.yml) runs it without installing the app.
 *
 *   node scripts/docs-components.mjs
 *   DOCS_FEED_ORIGIN=http://localhost:3006 node scripts/docs-components.mjs
 *   DOCS_FEED_FILE=/tmp/feed.json node scripts/docs-components.mjs
 */
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { scanKits } from "./docs-components-scan.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const SITE = path.join(ROOT, "docs", "site");
const DIR = path.join(SITE, "components");
const CSS = path.join(SITE, "brand-components.css");
const CONFIG = path.join(SITE, "docs.json");
const TAB = "Components";
const ORIGIN = process.env.DOCS_FEED_ORIGIN ?? "https://www.dallaspeters.com";
/** Marks a page this script owns, so a page written by hand is never removed. */
const MARK = "{/* Generated by scripts/docs-components.mjs. Do not edit. */}";

const KIND_LABEL = {
  accordion: "Accordion",
  avatar: "Avatar",
  badge: "Badge",
  button: "Button",
  card: "Card",
  checkbox: "Checkbox",
  dialog: "Dialog",
  divider: "Divider",
  icon: "Icon",
  input: "Input",
  label: "Label",
  link: "Link",
  logo: "Logo",
  menu: "Menu",
  navbar: "Navbar",
  panel: "Panel",
  progress: "Progress",
  select: "Select",
  skeleton: "Skeleton",
  table: "Table",
  tabs: "Tabs",
  tag: "Tag",
  text: "Text",
  textarea: "Text area",
  toast: "Toast",
  tooltip: "Tooltip",
};

/** Text inside MDX: braces and angle brackets would be read as code. */
const mdxText = (value) =>
  value.replace(/[{}<>]/g, (c) => `&#${c.charCodeAt(0)};`);
const yamlString = (value) => JSON.stringify(value);

/** Native nesting scopes each rule, including rules inside media queries. */
const scopeSourceCss = (source, slug) => `.bk-${slug} {\n${source.css}\n}`;

const scopedCss = (kit) =>
  kit.components
    .map(({ source }) => scopeSourceCss(source, kit.slug))
    .join("\n");

const fence = (lang, title, code) =>
  `\`\`\`${lang} ${title}\n${code.trimEnd()}\n\`\`\``;

/**
 * Each preview is a page widget: the page's own HTML keeps only a few tags
 * (a card's <article>, tabs' <nav>, <select> and <textarea> came out empty),
 * and a widget renders any element. `not-prose` keeps the docs' typography
 * off the component.
 */
const SUMMARY_CONTENT = /(<summary[^>]*>)[^\n]*/;
const PANEL_OPEN = /data-panel-open="(true|false)"/;
const PANEL_EXPANDED = /aria-expanded=\{(?:true|false)\}/;
const widgetOf = (source) => {
  const panel = source.preview.match(PANEL_OPEN);
  if (
    panel &&
    source.preview.includes(`className="${source.className}__trigger"`)
  ) {
    const markup = source.preview
      .replace(PANEL_OPEN, "data-panel-open={open} inert={!open}")
      .replace(
        PANEL_EXPANDED,
        "aria-expanded={open} onClick={() => setOpen(!open)}"
      );
    return widgetMarkup(
      source,
      markup,
      `  const [open, setOpen] = useState(${panel[1]});`
    );
  }
  const interactive = source.previewValue !== undefined;
  const preview = interactive
    ? source.preview
        .replace(SUMMARY_CONTENT, "$1{value}")
        .replaceAll(
          ' type="button"',
          ' type="button" onClick={(event) => { setValue(event.currentTarget.textContent ?? ""); event.currentTarget.closest("details")?.removeAttribute("open"); }}'
        )
    : source.preview;
  return widgetMarkup(
    source,
    preview,
    interactive
      ? `  const [value, setValue] = useState(${JSON.stringify(source.previewValue)});`
      : ""
  );
};

const widgetMarkup = (source, preview, state) => {
  const start = state ? `() => {\n${state}\n  return (` : "() => (";
  const end = state ? ");\n};" : ");";
  return `export const Preview${source.name} = ${start}\n  <div className="not-prose bk-preview bk-${source.slug}"${source.previewBackground ? ` style={{ background: ${JSON.stringify(source.previewBackground)} }}` : ""}>\n    <style>{${JSON.stringify(`${source.fonts.map((href) => `@import url(${JSON.stringify(href)});`).join("\n")}\n${BASE_CSS}\n${scopeSourceCss(source, source.slug)}`)}}</style>\n${preview
    .split("\n")
    .map((line) => `    ${line}`)
    .join("\n")}\n  </div>\n${end}`;
};

/** axe writes a required ratio as "4.5:1". */
const RATIO_SUFFIX = /:1$/;

const unique = (items) => [...new Set(items)];

/** One component's accessibility result, as a callout under its preview. */
const a11yBlock = (result, version) => {
  if (!result) {
    return "";
  }
  const manual = result.incomplete.length
    ? `\n\nNeeds a person to check: ${result.incomplete.map((rule) => mdxText(rule.help)).join("; ")}.`
    : "";
  if (result.violations.length === 0) {
    return `<Check>\n**Accessibility: no issues found.** axe-core ${version} passed ${result.passes} WCAG 2.2 AA ${result.passes === 1 ? "check" : "checks"} on this component.${manual}\n</Check>`;
  }
  const lines = result.violations.map((rule) => {
    const contrast = unique(
      rule.nodes
        .filter((node) => node.ratio)
        .map(
          (node) =>
            `${node.ratio}:1, needs ${node.expected.replace(RATIO_SUFFIX, "")}:1 (${node.foreground} on ${node.background})`
        )
    );
    const detail = contrast.length
      ? contrast.join("; ")
      : `${rule.nodes.length} ${rule.nodes.length === 1 ? "element" : "elements"}`;
    return `- **${mdxText(rule.help)}** (${rule.impact}): ${mdxText(detail)}. [About this rule](${rule.helpUrl})`;
  });
  const count = result.violations.length;
  return `<Warning>\n**Accessibility: ${count} ${count === 1 ? "issue" : "issues"}** found by axe-core ${version} (WCAG 2.2 AA).\n\n${lines.join("\n")}${manual}\n</Warning>`;
};

const passing = (kit, scan) =>
  kit.components.filter(
    ({ source }) =>
      scan.results[kit.slug]?.[source.className]?.violations.length === 0
  ).length;

const kitPage = (kit, scan) => {
  const sections = kit.components.map(({ kind, name, source }) =>
    [
      `## ${mdxText(`${KIND_LABEL[kind] ?? kind} · ${name}`)}`,
      "",
      `<Preview${source.name} />`,
      "",
      a11yBlock(scan.results[kit.slug]?.[source.className], scan.version),
      "",
      "<CodeGroup>",
      fence("tsx", `${source.name}.tsx`, source.tsx),
      "",
      fence("css", `${source.name}.css`, source.css),
      "</CodeGroup>",
    ].join("\n")
  );
  const widgets = kit.components.map(({ source, previewBackground }) =>
    widgetOf({
      ...source,
      fonts: kit.fonts ?? [],
      previewBackground,
      slug: kit.slug,
    })
  );
  const count = kit.components.length;
  return `---
title: ${yamlString(kit.name)}
description: ${yamlString(`${count} ${count === 1 ? "component" : "components"} from the ${kit.name} brand kit, as React and CSS to copy.`)}
---

${MARK}

Each component below is drawn with the ${mdxText(kit.name)} brand kit's style. Copy the React file and its CSS into your project. The look is in the custom properties at the top of the CSS.

**Accessibility:** ${passing(kit, scan)} of ${count} components pass an automated scan with axe-core ${scan.version} against WCAG 2.2 AA. Each component is scanned in a browser as drawn here, at rest. Hover and focus states, keyboard use and screen reader output still need a person to check.

${sections.join("\n\n")}

${kit.components.some(({ source }) => source.previewValue !== undefined) ? 'import { useState } from "react";\n\n' : ""}${widgets.join("\n\n")}
`;
};

const indexPage = (kits, scan) => `---
title: "Components"
description: "Brand kit components as React and CSS, ready to copy."
---

${MARK}

Every brand kit with component styles has a page here. A kit's page updates when its styles change in Studio, and each component is scanned for accessibility (axe-core ${scan.version}, WCAG 2.2 AA) every time.

<CardGroup cols={2}>
${kits
  .map(
    (kit) =>
      `  <Card title=${yamlString(kit.name)} href="/components/${kit.slug}">\n    ${kit.components.length} ${kit.components.length === 1 ? "component" : "components"}. ${passing(kit, scan)} pass the accessibility scan.\n  </Card>`
  )
  .join("\n")}
</CardGroup>
`;

/** Shared preview frame; each kit's own rules follow. */
const BASE_CSS = `/* Generated by scripts/docs-components.mjs. Do not edit. */
.bk-preview {
  display: flex;
  flex-wrap: wrap;
  align-items: flex-start;
  gap: 1rem;
  padding: 2rem;
  margin: 1rem 0;
  border: 1px solid rgb(127 127 127 / 0.2);
  border-radius: 0.75rem;
  background: #fff;
  overflow-x: auto;
  /* A light box on a dark page: native controls (a select's list, a
     checkbox) draw light, as they do where the kit is used. */
  color-scheme: light;
}

/*
 * The docs theme stops at the preview. Its typography reaches inside even
 * with not-prose: in the dark theme bold text turned near-white, so card
 * and panel titles vanished on the white box, and table rows took its
 * rules. Those rules are in a cascade layer, so these plain ones win over
 * them, while each component's own rules (two classes) still win over these.
 */
.bk-preview :is(strong, b) {
  color: inherit;
}

.bk-preview :is(thead, tbody, tr) {
  border: 0;
}

/* The theme's checkbox margin is not layered; this outweighs it. */
.bk-preview input[type="checkbox"] {
  margin: 0;
}

/* Keep open menus inside the preview, including Mintlify's snippet frame. */
.bk-preview details[open] > [class$="__list"] {
  position: static;
  margin-block-start: 4px;
}
`;

const setNavigation = (kits) => {
  const config = JSON.parse(readFileSync(CONFIG, "utf8"));
  const tabs = config.navigation.tabs.filter((tab) => tab.tab !== TAB);
  if (kits.length > 0) {
    tabs.push({
      groups: [
        { group: "Overview", pages: ["components/index"] },
        { group: "Brands", pages: kits.map((kit) => `components/${kit.slug}`) },
      ],
      tab: TAB,
    });
  }
  // Written only when the tab changed: the formatter lays this file out its
  // own way, and rewriting it unchanged would commit on every run.
  if (JSON.stringify(tabs) === JSON.stringify(config.navigation.tabs)) {
    return;
  }
  config.navigation.tabs = tabs;
  writeFileSync(CONFIG, `${JSON.stringify(config, null, 2)}\n`);
};

/** The feed: from the site, or from a saved copy (DOCS_FEED_FILE) to try a page. */
const readFeed = async () => {
  if (process.env.DOCS_FEED_FILE) {
    return JSON.parse(readFileSync(process.env.DOCS_FEED_FILE, "utf8"));
  }
  // The public endpoint is CDN-cached for visitors. Each scheduled build must
  // read the latest kit, including a change saved just before this run.
  const url = `${ORIGIN}/api/brand-kits?docs=components&build=${Date.now()}`;
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`${url} answered ${res.status}`);
  }
  return res.json();
};

const main = async () => {
  const { kits } = await readFeed();

  mkdirSync(DIR, { recursive: true });
  const keep = new Set(["index.mdx", ...kits.map((kit) => `${kit.slug}.mdx`)]);
  for (const file of readdirSync(DIR)) {
    const full = path.join(DIR, file);
    if (!keep.has(file) && readFileSync(full, "utf8").includes(MARK)) {
      rmSync(full);
    }
  }
  // @import has to come first in a stylesheet.
  const fonts = [...new Set(kits.flatMap((kit) => kit.fonts ?? []))]
    .map((href) => `@import url(${JSON.stringify(href)});`)
    .join("\n");
  const css = `${fonts ? `${fonts}\n\n` : ""}${BASE_CSS}\n${kits.map(scopedCss).join("\n")}`;
  // Scanned with the same CSS the pages load, so the result is the page's.
  const scan = await scanKits(kits, { css });
  for (const kit of kits) {
    writeFileSync(path.join(DIR, `${kit.slug}.mdx`), kitPage(kit, scan));
  }
  writeFileSync(path.join(DIR, "index.mdx"), indexPage(kits, scan));
  writeFileSync(CSS, css);
  setNavigation(kits);

  // Record the exact snapshot only after generation and the scan succeeded.
  if (process.env.DOCS_FEED_HASH_FILE) {
    writeFileSync(
      path.join(SITE, ".component-feed-hash"),
      readFileSync(process.env.DOCS_FEED_HASH_FILE, "utf8")
    );
  }

  const total = kits.reduce((n, kit) => n + kit.components.length, 0);
  const passed = kits.reduce((n, kit) => n + passing(kit, scan), 0);
  process.stdout.write(
    `docs components: ${kits.length} kits, ${total} components, ${passed} pass the accessibility scan.\n`
  );
};

await main();
