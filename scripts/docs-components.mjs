/**
 * Writes the docs site's Components tab from the brand kits.
 *
 * Reads the public feed (`/api/brand-kits?docs=components`) and writes one
 * page per kit with component styles: each style drawn live, then its React
 * and CSS in a code group with Mintlify's copy button. A kit gets a page as
 * soon as it has a style, and loses it when it has none.
 *
 * Plain Node, no dependencies, so the scheduled workflow
 * (.github/workflows/docs-components.yml) runs it without installing the app.
 *
 *   node scripts/docs-components.mjs
 *   DOCS_FEED_ORIGIN=http://localhost:3006 node scripts/docs-components.mjs
 *   DOCS_FEED_FILE=/tmp/feed.json node scripts/docs-components.mjs
 */
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SITE = path.join(ROOT, "docs", "site");
const DIR = path.join(SITE, "components");
const CSS = path.join(SITE, "brand-components.css");
const CONFIG = path.join(SITE, "docs.json");
const TAB = "Components";
const ORIGIN = process.env.DOCS_FEED_ORIGIN ?? "https://www.dallaspeters.com";
/** Marks a page this script owns, so a page written by hand is never removed. */
const MARK = "{/* Generated by scripts/docs-components.mjs. Do not edit. */}";

const KIND_LABEL = {
  badge: "Badge",
  button: "Button",
  card: "Card",
  checkbox: "Checkbox",
  dialog: "Dialog",
  divider: "Divider",
  icon: "Icon",
  input: "Input",
  label: "Label",
  link: "Link",
  menu: "Menu",
  panel: "Panel",
  progress: "Progress",
  select: "Select",
  skeleton: "Skeleton",
  table: "Table",
  tabs: "Tabs",
  tag: "Tag",
  text: "Text",
  textarea: "Text area",
  toast: "Toast",
};

/** Text inside MDX: braces and angle brackets would be read as code. */
const mdxText = (value) =>
  value.replace(/[{}<>]/g, (c) => `&#${c.charCodeAt(0)};`);
const yamlString = (value) => JSON.stringify(value);

/** Every rule of a kit's CSS, scoped under its page's wrapper class. */
const scopedCss = (kit) =>
  kit.components
    .map(({ source }) =>
      source.css.replaceAll(
        `.${source.className}`,
        `.bk-${kit.slug} .${source.className}`
      )
    )
    .join("\n");

const fence = (lang, title, code) =>
  `\`\`\`${lang} ${title}\n${code.trimEnd()}\n\`\`\``;

const kitPage = (kit) => {
  const sections = kit.components.map(({ kind, name, source }) =>
    [
      `## ${mdxText(`${KIND_LABEL[kind] ?? kind} · ${name}`)}`,
      "",
      `<div className="bk-preview bk-${kit.slug}">`,
      source.preview,
      "</div>",
      "",
      "<CodeGroup>",
      fence("tsx", `${source.name}.tsx`, source.tsx),
      "",
      fence("css", `${source.name}.css`, source.css),
      "</CodeGroup>",
    ].join("\n")
  );
  const count = kit.components.length;
  return `---
title: ${yamlString(kit.name)}
description: ${yamlString(`${count} ${count === 1 ? "component" : "components"} from the ${kit.name} brand kit, as React and CSS to copy.`)}
---

${MARK}

Each component below is drawn with the ${mdxText(kit.name)} brand kit's style. Copy the React file and its CSS into your project. The look is in the custom properties at the top of the CSS.

${sections.join("\n\n")}
`;
};

const indexPage = (kits) => `---
title: "Components"
description: "Brand kit components as React and CSS, ready to copy."
---

${MARK}

Every brand kit with component styles has a page here. A kit's page updates when its styles change in Studio.

<CardGroup cols={2}>
${kits
  .map(
    (kit) =>
      `  <Card title=${yamlString(kit.name)} href="/components/${kit.slug}">\n    ${kit.components.length} ${kit.components.length === 1 ? "component" : "components"}\n  </Card>`
  )
  .join("\n")}
</CardGroup>
`;

/** Shared preview frame; each kit's own rules follow. */
const BASE_CSS = `/* Generated by scripts/docs-components.mjs. Do not edit. */
.bk-preview {
  display: flex;
  flex-wrap: wrap;
  align-items: flex-start;
  gap: 1rem;
  padding: 2rem;
  margin: 1rem 0;
  border: 1px solid rgb(127 127 127 / 0.2);
  border-radius: 0.75rem;
  background: #fff;
  overflow-x: auto;
}
`;

const setNavigation = (kits) => {
  const config = JSON.parse(readFileSync(CONFIG, "utf8"));
  const tabs = config.navigation.tabs.filter((tab) => tab.tab !== TAB);
  if (kits.length > 0) {
    tabs.push({
      groups: [
        { group: "Overview", pages: ["components/index"] },
        { group: "Brands", pages: kits.map((kit) => `components/${kit.slug}`) },
      ],
      tab: TAB,
    });
  }
  config.navigation.tabs = tabs;
  writeFileSync(CONFIG, `${JSON.stringify(config, null, 2)}\n`);
};

/** The feed: from the site, or from a saved copy (DOCS_FEED_FILE) to try a page. */
const readFeed = async () => {
  if (process.env.DOCS_FEED_FILE) {
    return JSON.parse(readFileSync(process.env.DOCS_FEED_FILE, "utf8"));
  }
  const url = `${ORIGIN}/api/brand-kits?docs=components`;
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`${url} answered ${res.status}`);
  }
  return res.json();
};

const main = async () => {
  const { kits } = await readFeed();

  mkdirSync(DIR, { recursive: true });
  const keep = new Set(["index.mdx", ...kits.map((kit) => `${kit.slug}.mdx`)]);
  for (const file of readdirSync(DIR)) {
    const full = path.join(DIR, file);
    if (!keep.has(file) && readFileSync(full, "utf8").includes(MARK)) {
      rmSync(full);
    }
  }
  for (const kit of kits) {
    writeFileSync(path.join(DIR, `${kit.slug}.mdx`), kitPage(kit));
  }
  writeFileSync(path.join(DIR, "index.mdx"), indexPage(kits));
  // @import has to come first in a stylesheet.
  const fonts = [...new Set(kits.flatMap((kit) => kit.fonts ?? []))]
    .map((href) => `@import url(${JSON.stringify(href)});`)
    .join("\n");
  writeFileSync(
    CSS,
    `${fonts ? `${fonts}\n\n` : ""}${BASE_CSS}\n${kits.map(scopedCss).join("\n")}`
  );
  setNavigation(kits);

  const total = kits.reduce((n, kit) => n + kit.components.length, 0);
  process.stdout.write(
    `docs components: ${kits.length} kits, ${total} components.\n`
  );
};

await main();
